"""Generate the compressed GUI bundle embedded into the main executable."""

import base64
import io
import textwrap
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GUI_DIR = ROOT / "gui"
OUTPUT = ROOT / "src" / "gui_bundle_data.py"


def main():
    buffer = io.BytesIO()
    with zipfile.ZipFile(
        buffer, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9
    ) as archive:
        for path in sorted(GUI_DIR.rglob("*")):
            if not path.is_file():
                continue
            relative = path.relative_to(GUI_DIR).as_posix()
            entry = zipfile.ZipInfo(relative, date_time=(2020, 1, 1, 0, 0, 0))
            entry.compress_type = zipfile.ZIP_DEFLATED
            entry.external_attr = 0o644 << 16
            archive.writestr(entry, path.read_bytes())

    encoded = base64.b64encode(buffer.getvalue()).decode("ascii")
    chunks = textwrap.wrap(encoded, 76)
    lines = [
        '"""Generated by scripts/embed_gui_bundle.py; do not edit manually."""',
        "",
        "GUI_BUNDLE_B64 = (",
        *(f'    "{chunk}"' for chunk in chunks),
        ")",
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    file_count = sum(1 for path in GUI_DIR.rglob("*") if path.is_file())
    print(f"Embedded {file_count} GUI files into {OUTPUT}")


if __name__ == "__main__":
    main()
